    "2026-02-16", "2026-02-17", "2026-02-18",  # 설날 연휴
    "2026-03-02",                              # 삼일절 대체공휴일
    "2026-05-01",                              # 근로자의 날(노동절)
    "2026-05-05",                              # 어린이날
    "2026-05-25",                              # 부처님오신날 대체공휴일
    "2026-06-03",                              # 전국동시지방선거
    "2026-08-17",                              # 광복절 대체공휴일
    "2026-09-24", "2026-09-25",                # 추석 연휴 (9/26 토)
    "2026-10-05",                              # 개천절 대체공휴일
    "2026-10-09",                              # 한글날
